/**
 * チャットの安全装置。LLMを通さず、決まった文章を返す・出力を検査するための純粋な関数。
 *
 * 重要な考え方: 危険な症状や、つらい気持ちの訴えに対して、LLMの自由な文章で返すのは危険
 * (言い回しが日によって変わる・診断めいた言い方をする・安心させすぎる)。
 * そのため、入力の段階でキーワードを検知し、確認済みの固定文を返す。
 * キーワードに頼る検知は取りこぼすので、これだけに頼らず、システムプロンプトにも同じ方針を書く。
 */

export type SafetyTrigger = "danger" | "selfHarm";

// 表記ゆれ(ひらがな・「息苦しい」「息ができない」等)を広めに拾う。多少の誤検知は許容する
// (誤検知しても「医療機関に連絡を」と促すだけで、害が小さいため)。
const DANGER_PATTERNS: RegExp[] = [
  /息(が|を)?(苦し|くるし|できな|出来な|吸えな|すえな|つまる|詰まる)/,
  /呼吸(が)?(苦し|くるし|困難|できな|出来な|しづら|しにく)/,
  /胸部?(が|を|の)?(痛|いた|苦し|くるし|締め|しめつ|圧迫|押され)/,
  /(意識|いしき)(が)?(遠|とお|もうろう|朦朧|おかし|ない|なく|失|飛)/,
  /失神|気を失|気絶|倒れ(た|そう)/,
  /動悸(が)?(ひどい|激しい|はげしい|強い|止まらな|とまらな)/,
  /(急に|急激に|突然)(むくみ|浮腫|腫れ|はれ)/,
  /(血|ち)を吐|吐血|喀血|下血|血便|血尿/,
  /(黒い|くろい)(便|うんち|ウンチ)|黒色便|タール便/,
  /出血(が)?(止まらな|とまらな|ひどい|多い|大量)/,
  /(激しい|ひどい|耐えられない|我慢できない)(腹痛|お腹の痛み|おなかの痛み)/,
];

const SELF_HARM_PATTERNS: RegExp[] = [
  /死にたい|しにたい|死のう|死んでしまいたい|死んだほうが|死んだ方が/,
  /消えたい|きえたい|いなくなりたい/,
  /自殺|自死|自傷|リスカ|リストカット/,
  /生きていたくない|生きる意味(が)?(ない|わからな|見いだせな)|生きていても(仕方|しかた)/,
  /(自分|じぶん)を(傷つけ|きずつけ)(たい|そう)/,
];

export function detectSafetyTrigger(text: string): SafetyTrigger | null {
  // 自傷・つらい気持ちの訴えを、身体症状より先に確認する
  if (SELF_HARM_PATTERNS.some((p) => p.test(text))) return "selfHarm";
  if (DANGER_PATTERNS.some((p) => p.test(text))) return "danger";
  return null;
}

/** 危険な症状が疑われる入力への固定文。診断はせず、医療機関への連絡を最優先で案内する */
export const DANGER_FIXED_REPLY =
  "いま書いてくださった内容は、このチャットでは判断できません。" +
  "息苦しさ・胸の痛みや圧迫感・意識がおかしい・強い動悸・急なむくみ・強い腹痛・" +
  "大量の出血や黒い便などの強い症状があるときは、チャットではなく、すぐに医療機関に連絡してください。" +
  "緊急性が高いと感じる場合は、ためらわず救急要請(119)も検討してください。" +
  "これは診断ではなく、症状の内容にかかわらず医療機関への連絡を優先してほしいという案内です。";

/**
 * つらい気持ちの訴えへの固定文。相談窓口の電話番号は、誤った番号を案内するリスクを避けるため、
 * 名称のみを書く(番号は利用者が公式サイトで確認する)。
 */
export const SELF_HARM_FIXED_REPLY =
  "つらい気持ちを話してくださって、ありがとうございます。いま、ひとりで抱え込まないでください。" +
  "身の危険を感じるときは、119に連絡するか、近くにいる人・主治医・医療機関にすぐ連絡してください。" +
  "気持ちを聞いてもらえる相談窓口(「いのちの電話」や「よりそいホットライン」など)もあります。" +
  "電話番号は変わることがあるため、公式サイトで確認してください。" +
  "このチャットはAIで、診断や治療の判断はできませんが、このことは主治医にも伝えてみてください。";

export function fixedReplyFor(trigger: SafetyTrigger): string {
  return trigger === "danger" ? DANGER_FIXED_REPLY : SELF_HARM_FIXED_REPLY;
}

// --- 出力の安全網 -----------------------------------------------------------------
// システムプロンプトで禁止していても、LLMが守らない可能性がある。明らかに越境した言い回しだけを
// 検知して、固定の案内に置き換える。完全ではない(言い換えは防げない)ので、あくまで最後の網。
// 否定形(「大丈夫とは言えません」等)を誤検知しないよう、断定の形だけを狙っている。

const FORBIDDEN_REPLY_PATTERNS: { reason: string; pattern: RegExp }[] = [
  { reason: "安心の断定", pattern: /大丈夫(です|ですよ|でしょう|だと思います|ですね)(?!か)|心配(いりません|はありません|ありません|ないです|不要)|問題(ありません|ないです|はありません)/ },
  { reason: "診断の断定", pattern: /診断(します|できます|されます|が確定)|(あなたは|これは|その症状は|それは)[^。]{0,20}(病|症候群|炎|MAS)(の再燃|の悪化|の症状|の発症)?(です|でしょう|だと思います|の可能性が高い)/ },
  { reason: "治療の指示", pattern: /(薬|ステロイド|プレドニン|プレドニゾロン|アクテムラ|メトトレキサート|NSAIDs?|ロキソニン).{0,20}(増や|減ら|やめ|止め|中止|変更|飲み始め|服用してください|飲んでください)/ },
  { reason: "緊急性の判定", pattern: /(これは|すぐに|今すぐ).{0,6}(緊急|危険)(です|な状態)|緊急事態です|危険な状態です/ },
];

export const REPLY_FALLBACK =
  "うまくお答えできませんでした(診断や治療の判断に踏み込んだ内容になりそうだったため、回答を控えました)。" +
  "このチャットは、記録から見えるパターンの整理だけを行います。" +
  "気になる点は、記録の画面やレポートを見せながら、主治医に相談してください。";

export interface SanitizedReply {
  reply: string;
  /** 置き換えた場合の理由(ログ・表示用)。置き換えなければnull */
  filteredReason: string | null;
}

export function sanitizeReply(reply: string): SanitizedReply {
  for (const { reason, pattern } of FORBIDDEN_REPLY_PATTERNS) {
    if (pattern.test(reply)) return { reply: REPLY_FALLBACK, filteredReason: reason };
  }
  return { reply, filteredReason: null };
}
