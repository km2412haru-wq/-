import type { ExamDomain, ExamGuide } from "@/types/quiz";

/**
 * Geminiへの system instruction(役割・出題ルールの固定部分)。
 * 全リクエスト共通。
 */
export function buildSystemInstruction(): string {
  return [
    "あなたはAWS認定資格試験の作問官です。実務経験豊富なソリューションアーキテクトとして、",
    "AWS公式試験ガイドの出題ドメインに基づいた、実務シナリオ形式の4択問題を新規に作成してください。",
    "",
    "厳守事項:",
    "- 市販の問題集・公式問題集・過去問を記憶から引用・模倣することは禁止。あくまで指定されたトピックの",
    "  知識に基づき、ゼロからオリジナルのシナリオ・問題文を創作すること。",
    "- 選択肢は必ず4つ。正解は1つのみ。誤りの選択肢は「一見もっともらしいが明確に誤り」と言えるものにする",
    "  (明らかに的外れな選択肢や、瑣末な言葉尻の違いだけの選択肢は避ける)。",
    "- 選択肢ごとに、なぜ正解/不正解なのかを簡潔かつ具体的に説明すること。",
    "- 問題文・選択肢・解説はすべて日本語。AWSのサービス名・機能名は正式な英語表記(例: Amazon S3, AWS IAM)を",
    "  そのまま使う。",
    "- 実在しないAWSサービス名や、不確かな料金・数値を断定的に書かないこと。",
    "- 出力は指定されたJSONスキーマに厳密に従うこと。JSON以外の文章(前置き・後書き等)は一切出力しないこと。",
  ].join("\n");
}

/**
 * 個別のリクエスト用プロンプト(資格・ドメイン・トピックを指定する部分)。
 *
 * Step2で「直近の出題履歴(トピック・要点一覧)を渡して重複を避けさせる」
 * パラメータをここに追加する予定。
 */
export function buildQuestionPrompt(params: {
  examGuide: ExamGuide;
  domain: ExamDomain;
  topics: string[];
}): string {
  const { examGuide, domain, topics } = params;

  return [
    `【対象資格】${examGuide.name}`,
    `【出題ドメイン】ドメイン${domain.id}: ${domain.name}(公式出題比率 ${domain.weight}%)`,
    `【出題トピック】${topics.join(" / ")}`,
    "",
    "上記のトピックを中心に据えた、実務シナリオ形式の4択問題を1問作成してください。",
    "",
    "出力するJSONの各フィールド:",
    "- keyConcept: この問題が問おうとしている要点を1文で(例:「クロスリージョンでのS3データ保護には",
    "  クロスリージョンレプリケーションが適切」)。今後の重複判定に使うため、問題の核心が分かる具体的な文にすること。",
    "- question: 問題文(実務シナリオを含む)",
    "- choices: 4つの選択肢の配列",
    "- correctIndex: 正解のインデックス(0〜3の整数、choices配列に対応)",
    "- explanationByChoice: choicesと同じ順・同じ長さの配列。各要素にその選択肢が正解/不正解である理由を書く",
  ].join("\n");
}
